//! Safe parser for Qualcomm `/mnt/vendor/persist/wlan_mac.bin` and deterministic
//! locally-administered fallback MAC generation for Xiaomi MIX 4 (`odin`).

use std::fmt;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MacAddr([u8; 6]);

impl MacAddr {
    pub fn from_bytes(bytes: [u8; 6]) -> Option<Self> {
        let all_zero = bytes.iter().all(|&b| b == 0);
        let all_ff = bytes.iter().all(|&b| b == 0xff);
        let is_multicast = (bytes[0] & 0x01) != 0;
        if all_zero || all_ff || is_multicast {
            return None;
        }
        Some(Self(bytes))
    }

    pub fn parse_hex12(s: &str) -> Option<Self> {
        let clean: String = s.chars().filter(|c| *c != ':' && *c != '-').collect();
        if clean.len() != 12 || !clean.chars().all(|c| c.is_ascii_hexdigit()) {
            return None;
        }
        let mut bytes = [0u8; 6];
        for (i, slot) in bytes.iter_mut().enumerate() {
            *slot = u8::from_str_radix(&clean[i * 2..i * 2 + 2], 16).ok()?;
        }
        Self::from_bytes(bytes)
    }

    /// Parse Qualcomm `wlan_mac.bin` text format (`Intf0MacAddress=AABBCCDDEEFF`).
    pub fn parse_wlan_mac_bin(contents: &str) -> Option<Self> {
        for raw_line in contents.lines() {
            let line = raw_line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            if let Some(rest) = line.strip_prefix("Intf0MacAddress=") {
                if let Some(mac) = Self::parse_hex12(rest.trim()) {
                    return Some(mac);
                }
            }
        }
        None
    }

    /// Deterministic locally-administered unicast MAC (`02:6f:64:XX:YY:ZZ`)
    /// derived from `androidboot.serialno` if `persist/wlan_mac.bin` is unreadable.
    pub fn from_serial_fallback(serial: &str) -> Self {
        // Simple FNV-1a 32-bit hash over serial string so any serial format works cleanly.
        let mut h: u32 = 0x811c_9dc5;
        for b in serial.trim().bytes() {
            h ^= u32::from(b);
            h = h.wrapping_mul(0x0100_0193);
        }
        Self([
            0x02, // locally administered (bit 1 = 1), unicast (bit 0 = 0)
            b'o',
            b'd',
            ((h >> 16) & 0xff) as u8,
            ((h >> 8) & 0xff) as u8,
            (h & 0xff) as u8,
        ])
    }

    /// Deterministic locally-administered unicast Bluetooth BD_ADDR (`02:62:74:XX:YY:ZZ`)
    /// derived from `androidboot.serialno` with domain separation from Wi-Fi MAC.
    pub fn bt_from_serial_fallback(serial: &str) -> Self {
        let mut h: u32 = 0x811c_9dc5;
        for b in b"bt:".iter().copied().chain(serial.trim().bytes()) {
            h ^= u32::from(b);
            h = h.wrapping_mul(0x0100_0193);
        }
        Self([
            0x02,
            b'b',
            b't',
            ((h >> 16) & 0xff) as u8,
            ((h >> 8) & 0xff) as u8,
            (h & 0xff) as u8,
        ])
    }

    pub fn extract_serial_from_cmdline(cmdline: &str) -> Option<&str> {
        for tok in cmdline.split_whitespace() {
            if let Some(val) = tok.strip_prefix("androidboot.serialno=") {
                if !val.is_empty() {
                    return Some(val);
                }
            }
        }
        None
    }

    pub fn networkmanager_conf(&self) -> String {
        format!(
            "# Generated by xiaomi-odin-firmware-util\n\
             [device-odin-ath11k]\n\
             wifi.scan-rand-mac-address=no\n\
             \n\
             [connection-odin-ath11k]\n\
             wifi.cloned-mac-address={self}\n\
             wifi.powersave=2\n"
        )
    }

    pub fn systemd_link_conf(&self) -> String {
        format!(
            "# Generated by xiaomi-odin-firmware-util\n\
             [Match]\n\
             Driver=ath11k_pci\n\
             \n\
             [Link]\n\
             NamePolicy=keep kernel\n\
             MACAddress={self}\n"
        )
    }
}

impl fmt::Display for MacAddr {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "{:02x}:{:02x}:{:02x}:{:02x}:{:02x}:{:02x}",
            self.0[0], self.0[1], self.0[2], self.0[3], self.0[4], self.0[5]
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_qualcomm_wlan_mac_bin() {
        let sample = "\
# Qualcomm Technologies Inc.
Intf0MacAddress=A45046123456
Intf1MacAddress=A65046123456
END
";
        let mac = MacAddr::parse_wlan_mac_bin(sample).expect("valid Intf0MacAddress");
        assert_eq!(mac.to_string(), "a4:50:46:12:34:56");
    }

    #[test]
    fn rejects_invalid_multicast_or_zero_mac() {
        assert_eq!(MacAddr::parse_wlan_mac_bin("Intf0MacAddress=000000000000\n"), None);
        assert_eq!(MacAddr::parse_wlan_mac_bin("Intf0MacAddress=FFFFFFFFFFFF\n"), None);
        assert_eq!(MacAddr::parse_wlan_mac_bin("Intf0MacAddress=015046123456\n"), None);
    }

    #[test]
    fn generates_valid_deterministic_fallback_mac() {
        let cmdline = "console=tty0 androidboot.serialno=964d14f0 rootwait";
        let serial = MacAddr::extract_serial_from_cmdline(cmdline).unwrap();
        assert_eq!(serial, "964d14f0");
        let m1 = MacAddr::from_serial_fallback(serial);
        let m2 = MacAddr::from_serial_fallback(serial);
        assert_eq!(m1, m2);
        assert_eq!(m1.0[0] & 0x03, 0x02); // locally administered unicast
    }
}
